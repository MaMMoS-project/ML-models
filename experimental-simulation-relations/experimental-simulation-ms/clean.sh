#!/bin/bash -l
# =============================================================================
# clean.sh  --  remove everything the pipeline (run_1node-RE*.sh) generates,
#               so a fresh run starts from the raw / preprocessed inputs only.
#
# USAGE:
#   ./clean.sh              show what would be removed, then ask for confirmation
#   ./clean.sh -y|--yes     delete without asking
#   ./clean.sh -n|--dry-run only list what would be removed, delete nothing
#
# -----------------------------------------------------------------------------
# DELETES  (every artifact a pipeline run regenerates):
#   data/merged_df_python.csv        step 1  build_merged_dataset
#   outputs/                         augment_data CSVs (Augm_combined_*, Pairs_*),
#                                    compound-embedding + PCA .pkl files,
#                                    t-SNE / distribution plots,
#                                    PySR symbolic-regression run dirs (2026*_*)
#   results/                         all per-family results, comparison tables,
#                                    parity plots, diagnostics, results/figures/
#   logs/*.txt                       per-step run logs (augment_data.txt, ...)
#   figures/                         deliverable parity figures
#                                    (regenerated by make_deliverable_parity_figures.py)
#
# PRESERVES  (inputs, backups, sources, SLURM output -- NEVER deleted):
#   RE*.out.*  /  RE*.err.*          SLURM job output        <-- kept on purpose
#   preprocessed_data/               input Ms tables (Experimental_/Simulated_*)
#   data/raw/                        raw source databases
#   data/embeddings/                 matscholar200 element embedding (input)
#   data/*.bak  /  *.OLD-*           manual backups
#   logs-before-cv/ logs-no-delta/ logs.BAK/   manual log archives
#   src/  run_1node-*.sh  *.py  *.md  create_data/  my-tc/  demonstrator_notebook/
# =============================================================================

set -u

# Always operate on the project that holds this script, wherever it is invoked.
cd "$(dirname "$(readlink -f "$0")")" || { echo "cannot cd to script dir"; exit 1; }

DRY_RUN=0
ASSUME_YES=0
case "${1:-}" in
    -n|--dry-run) DRY_RUN=1 ;;
    -y|--yes)     ASSUME_YES=1 ;;
    "")           ;;
    *) echo "Unknown option: $1"; echo "Usage: $0 [-y|--yes] [-n|--dry-run]"; exit 2 ;;
esac

echo "Project: $(pwd)"
echo

# --- Targets -----------------------------------------------------------------
# Whole directories whose entire contents are pipeline-generated.
DIR_TARGETS=(outputs results figures)
# Individual generated files / globs.
FILE_TARGETS=(data/merged_df_python.csv)
# Glob of generated run logs (keeps the logs/ dir and the logs-*/logs.BAK archives).
LOG_GLOB=(logs/*.txt)

echo "The following pipeline artifacts will be removed:"
for d in "${DIR_TARGETS[@]}"; do
    if [ -d "$d" ]; then
        n=$(find "$d" -mindepth 1 2>/dev/null | wc -l)
        printf "   %-34s (%s entries)\n" "$d/" "$n"
    fi
done
for f in "${FILE_TARGETS[@]}"; do
    [ -e "$f" ] && printf "   %-34s\n" "$f"
done
shopt -s nullglob
loglist=("${LOG_GLOB[@]}")
shopt -u nullglob
[ "${#loglist[@]}" -gt 0 ] && printf "   %-34s (%s files)\n" "logs/*.txt" "${#loglist[@]}"

echo
echo "Preserved: SLURM output (RE*.out.* / RE*.err.*), preprocessed_data/, data/raw/,"
echo "           data/embeddings/, *.bak / *.OLD-*, logs-*/ logs.BAK/, src/, my-tc/, scripts."
echo

if [ "$DRY_RUN" -eq 1 ]; then
    echo "[dry-run] nothing deleted."
    exit 0
fi

if [ "$ASSUME_YES" -ne 1 ]; then
    printf "Proceed with deletion? [y/N] "
    read -r reply
    case "$reply" in
        y|Y|yes|YES) ;;
        *) echo "Aborted."; exit 0 ;;
    esac
fi

# --- Delete ------------------------------------------------------------------
for d in "${DIR_TARGETS[@]}"; do
    if [ -d "$d" ]; then
        rm -rf "${d:?}"/* "${d:?}"/.[!.]* 2>/dev/null
        echo "cleared $d/"
    fi
done
for f in "${FILE_TARGETS[@]}"; do
    if [ -e "$f" ]; then
        rm -f "$f"
        echo "removed $f"
    fi
done
if [ "${#loglist[@]}" -gt 0 ]; then
    rm -f "${loglist[@]}"
    echo "removed logs/*.txt (${#loglist[@]} files)"
fi

echo
echo "Done. Re-run the pipeline with ./run_1node-RE-delta.sh (or ./run_1node-RE.sh)."
